def 中身だけ(文):
    """記事の本文から「更新日：…」より後ろ＝実際の中身を取る。
       ★これをしないと、パンくずと題の繰り返しを読み上げてしまう"""
    m = re.search(r"更新日：\d{4}年\d{1,2}月\d{1,2}日\s*", 文 or "")
    t = 文[m.end():] if m else (文 or "")
    for 印 in ("関係リンク", "関連リンク", "この記事に関するお問い合わせ",
               "PDFファイルを閲覧するには", "よりよいウェブサイトにするために"):
        i = t.find(印)
        if i > 40:
            t = t[:i]
    return t.strip()


def 雑を落とす(t):
    """読み上げに邪魔なもの（PDFの案内・ダウンロードの誘導）を消す。
       ★2026-08-27：これをしないと「(PDFファイル: 4.6MB)」まで読み上げ、
         肝心の中身に文字数を使えなかった"""
    t = re.sub(r"[（(]\s*(PDF|Word|Excel)ファイル[^）)]*[）)]", "", t)
    # ★「楽譜(PDF:389.5KB)」「(音声ファイル:2.2MB)」「(ミュージック:4.8MB)」の形も落とす
    t = re.sub(r"[（(]\s*(PDF|音声ファイル|ミュージック|Word|Excel)\s*[:：][^）)]*[）)]", "", t)
    t = re.sub(r"歌詞・楽譜|音声ダウンロード|歌詞・楽譜ダウンロード", "", t)
    # ★全角の括弧や「ファイル:」の無い形も落とす（2026-08-27に検査が見つけた：
    #   市歌に「(PDFファイル: 1.2MB)」が残り、そのまま読み上げていた）
    t = re.sub(r"[（(][^）)]{0,20}(PDF|音声|ミュージック|Word|Excel)[^）)]{0,20}[）)]", "", t)
    t = re.sub(r"\S*\.(pdf|mp3|wav|docx?|xlsx?)\b", "", t, flags=re.I)
    for 印 in ("全編はこちらからご覧ください", "テキスト全文", "ダウンロード",
               "こちらからご覧ください", "ぜひご覧ください"):
        t = t.replace(印, "")
    return re.sub(r"[ 　]{2,}", " ", t)


def 抜き出す(中身, 手がかり, 上限=420, 後ろだけ=False):
    """手がかりの言葉を含む文を、前後の流れごと拾う。手で書かない"""
    中身 = 雑を落とす(中身)
    # ★ダウンロードや申込の案内を含む文は、丸ごと外す（2026-08-27に検査が見つけた：
    #   市歌に「歌詞と楽譜は次のPDFファイルを…」が残り、そのまま読み上げていた）。
    #   括弧の中だけを消しても、文の途中にあるものは残る
    捨てる = re.compile(r"PDF|ダウンロード|申込フォーム|貸出申込|ご覧ください|クリック|"
                        r"ファイルを閲覧|Adobe|こちらから")
    # ★日付や期間が書いてある文は捨てない（2026-08-27の実測）。
    #   「申告期間中（2月16日～3月16日）は、次のページもご覧ください」が
    #   『ご覧ください』を理由に捨てられ、肝心の申告期間が落ちていた
    大事 = re.compile(r"\d{1,2}月\d{1,2}日|申告期間|受付期間|開館時間|営業時間")
    出来 = []
    for x in re.split(r"(?<=。)", 中身):
        x = x.strip()
        if not x:
            continue
        if 捨てる.search(x):
            if not 大事.search(x):
                continue
            # ★大事な日付を含むが案内も混じっている文は、案内の「後ろ」だけ落とす。
            #   ★文の頭から消してはいけない（2026-08-27の失敗）。
            #     「また、申告期間中（2月16日～3月16日）は、次のページもご覧ください。」が
            #     丸ごと消えて「。」だけになり、確定申告の項目そのものが作れなくなった。
            #     案内の言葉が始まる所で切って、前半（日付のある方）を残す
            m2 = re.search(r"(PDF|ダウンロード|申込フォーム|ご覧ください|クリック|"
                           r"ファイルを閲覧|Adobe|こちらから)", x)
            if m2:
                前 = x[:m2.start()]
                # 直前の読点・「次の」などで切って、言い差しにしない
                前 = re.sub(r"[、,]\s*(次の|下記の|以下の)?[^、。]*$", "", 前).strip()
                # ★助詞で終わると「…3月16日）は。」のように尻切れになる（実測）。
                #   その場合は、その節を丸ごと落として前の文だけ残す
                前 = re.sub(r"[はがをにでとへもや、，]+$", "", 前).strip()
                x = (前 + "。") if len(前) >= 8 else ""
            x = x.strip()
            if len(x) < 8:
                continue
        出来.append(x)
    文ら = 出来
    出, 使 = [], 0
    for i, 文 in enumerate(文ら):
        if not re.search(手がかり, 文):
            continue
        範囲 = (i, i + 1, i + 2, i + 3) if 後ろだけ else (i - 1, i, i + 1, i + 2, i + 3)
        for j in 範囲:   # ★核心は手がかりの後に続くことが多い
            if 0 <= j < len(文ら) and 文ら[j] not in 出:
                if 使 + len(文ら[j]) > 上限:
                    break
                出.append(文ら[j]); 使 += len(文ら[j])
        if 使 >= 上限:
            break
    return "".join(出)


