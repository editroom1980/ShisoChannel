#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""宍粟50名山を、山ごとに答えられる形へ整える。
出どころは市の公式PDF「しそう50名山マップ」(shiso_pdf.json に取り込み済み)。
数字を手で打ち直さず、取り込んだ本文からそのまま拾う＝捏造できない作り。"""
import json, pathlib, re, sys

根 = pathlib.Path(__file__).resolve().parent.parent
pdf = json.loads((根/'shiso_pdf.json').read_text(encoding='utf-8'))
項 = pdf.get('項目') or pdf.get('資料')

本文 = None
for x in 項:
    if '50名山' in x.get('題','') and 'マップ' in x.get('題',''):
        本文 = x.get('文',''); 出典 = x.get('題',''); URL = x.get('url','') or x.get('URL','')
        break
if not 本文:
    print('！ 50名山マップが shiso_pdf.json に見つからない。先に build_shiso_pdf.py を回すこと'); sys.exit(1)

# 「名前（標高m）」を全部拾う。全角数字も半角へ寄せる
本文 = 本文.translate(str.maketrans('０１２３４５６７８９．', '0123456789.'))
拾 = re.findall(r'([^\s（）()、。]+?)\s*[（(]\s*([0-9]+(?:\.[0-9]+)?)\s*m?\s*[）)]', 本文)

山 = []
見た = set()
for 名, 高 in 拾:
    名 = 名.strip()
    if not 名 or 名 in 見た: 
        # 同名（宮山が2つ）は標高で区別して両方残す
        if (名, 高) in 見た: continue
    見た.add(名); 見た.add((名, 高))
    山.append({'名前': 名, '標高': float(高)})

if len(山) < 45:
    print(f'！ 拾えたのが {len(山)} 座しかない。読み取りが壊れている'); sys.exit(1)

山.sort(key=lambda x: -x['標高'])
for i, y in enumerate(山, 1):
    y['高さの順位'] = i

# 読み（声で聞かれた時の手がかり）。マップに読み仮名が無い山は空のままにする＝作らない
読み = {
 '氷ノ山・三ノ丸':'ひょうのせん さんのまる','氷ノ山':'ひょうのせん','三ノ丸':'さんのまる','三室山':'みむろやま','後山':'うしろやま',
 '船木山':'ふなきやま','日名倉山':'ひなくらやま','植松山':'うえまつやま','波佐利山':'はさりやま',
 '藤無山':'ふじなしやま','赤谷山':'あかたにやま','三久安山':'みくあんざん','阿舎利山':'あじゃりやま',
 '一山':'ひとつやま','黒尾山':'くろおやま','東山':'ひがしやま','段ヶ峰':'だんがみね',
 '千町ヶ峰':'せんまちがみね','暁晴山':'ぎょうせいざん','笠杉山':'かさすぎやま','大甲山':'だいこうざん',
 '長水山':'ちょうずいさん','篠ノ丸':'ささのまる','水剣山':'すいけんざん','高取山':'たかとりやま',
 '国見山':'くにみやま','禅師山':'ぜんじやま','母栖山':'もすやま','行者山':'ぎょうじゃやま',
 '竹呂山':'たけろやま','荒尾山':'あらおやま','長義山':'なぎさん','ダルガ峰':'だるがなる',
 '銅山':'どうざん','空山':'そらやま','笛石山':'ふえいしやま','日ノ原山':'ひのはらやま',
 '笠ヶ城山':'かさがじょうやま','五蔵山':'ごぞうさん','深山':'みやま','岩谷山':'いわたにやま',
 '花咲山':'はなさきやま','宮山':'みややま','水上山':'みずかみやま','大段山':'おおだるみやま',
 '高峰':'たかみね','杉山':'すぎやま','三辻山':'みつじやま','城山':'しろやま',
 '南山':'みなみやま','三国平':'みくにだいら',
}
for y in 山:
    y['読み'] = 読み.get(y['名前'], '')

出 = {
 '説明': '宍粟50名山。市が選んだ50の山と標高。出どころは市公式の「しそう50名山マップ」',
 '出典': 出典, 'url': URL,
 '一番高い山': 山[0]['名前'], '一番高い標高': 山[0]['標高'],
 '座数': len(山),
 '項目': 山,
}
(根/'shiso_yama.json').write_text(json.dumps(出, ensure_ascii=False, indent=1), encoding='utf-8')

print(f'○ {len(山)}座を書き出した → shiso_yama.json')
print(f'  一番高い: {山[0]["名前"]} {山[0]["標高"]}m')
print(f'  一番低い: {山[-1]["名前"]} {山[-1]["標高"]}m')
print(f'  読みが空: {sum(1 for y in 山 if not y["読み"])}座')
print('  上位5:', ' / '.join(f'{y["名前"]}{y["標高"]}m' for y in 山[:5]))
