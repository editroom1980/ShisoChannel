# -*- coding: utf-8 -*-
"""宍粟市の助成・補助・給付の一覧

なぜ：
  市民がいちばん知りたいのは「うちは何がもらえるのか」。
  市の記事は104件あるが、ばらばらに置かれていて
  「どんな助成がありますか」「子育ての補助は」に一覧で答えられなかった。

★金額・対象は市の記事に書いてある通りに写す。こちらで作らない。
  書いていないものは「記事を見てください」とだけ言えるようにする。
"""
import json, pathlib, re, sys
import sys as _sys, os as _os
_sys.path.insert(0, _os.path.dirname(_os.path.abspath(__file__)))
from kensan import 件数を守る
from collections import Counter

根 = pathlib.Path(__file__).resolve().parent.parent

# ★「学校」だけで子育てに入れない。学校の設備や地域行事の助成も当たってしまう。
#   上の分けでは「学校給食」「通学」「就学」のように、子どもへの助成と分かる形にした
# 助成の記事かどうか（題で見る）
拾う = re.compile(r"助成|補助|給付|支援金|奨励金|報奨金|手当|無料|減免|免除|貸付")
# 助成の案内ではないもの（事業者向けの募集要項・審査結果など）
除く = re.compile(r"審査結果|プロポーザル|入札|委託|事業者募集|要綱の一部|議案|"
                  r"パブリックコメント|実施結果|計画|条例|規則|様式")

# 暮らしの場面での分け方（市民が探す言葉で分ける）
分け = [
    # ★「子ども会」「PTA」は地域活動であって子育ての助成ではない（2026-08-28の実測：
    #   「リサイクル資源 集団回収に奨励金」が子育ての助成として案内された）。
    #   ★『子ども』の直後が『会』なら数えない
    ("子育て", r"子ども(?!会)|こども(?!会)|子育て|児童|乳幼児|妊婦|出産|保育|幼稚|"
               r"入学|通学|就学|学校給食|奨学"),
    ("高齢者", r"高齢|介護|敬老|後期高齢|認知症|老人"),
    ("障がい", r"障害|障がい|手帳|補装具|自立支援"),
    ("健康・医療", r"医療|検診|健診|接種|ワクチン|がん|歯|不妊|治療|health"),
    ("住まい", r"住宅|住まい|空き家|耐震|リフォーム|改修|移住|定住|家賃"),
    # ★「事業」だけで拾わない（2026-08-28の実測：「介護給付費等の算定に係る
    #   体制等に関する届出書」まで『しごと』に入り、74件に膨れた）。
    #   はたらくことに直に関わる言葉だけにする
    ("しごと", r"就労|就職|創業|起業|商工業|中小企業|事業者|雇用|職業訓練|"
               r"農業経営|林業|担い手|移住就業|インターンシップ|人材"),
    ("暮らし・安全", r"ごみ|生ごみ|浄化槽|水道|防災|防犯|消防|スズメバチ|animals|犬|道路|水路|除雪"),
]

def 場面(題, 文):
    """★題を主に見る。題で1つも当たらないときだけ本文を見るが、
       本文の先頭はパンくず（くらし・手続き 環境 …）と題の繰り返しなので飛ばす。
       ★実測：「リサイクル資源 集団回収に奨励金」の本文に『子ども会』とあり、
         子育ての助成として案内してしまった（2026-08-28）"""
    t = 題
    if not any(re.search(型, t) for _, 型 in 分け):
        # パンくずと題の繰り返しを飛ばして、本文の中身から見る
        本 = 文
        i = 本.find("更新日：")
        if i > 0: 本 = 本[i + 14:]
        t = 題 + " " + 本[:150]
    出 = []
    for 名, 型 in 分け:
        if re.search(型, t): 出.append(名)
    return 出 or ["そのほか"]

def 金額(文):
    """記事に書いてある金額を拾う。★いちばん最初に出てくる『◯円』の周りを写す"""
    m = re.search(r"[^。\n]{0,36}([\d,]{3,9})\s*円[^。\n]{0,24}", 文)
    return re.sub(r"\s+", "", m.group(0))[:70] if m else ""

def 主():
    kb = json.loads((根 / "shiso_kb.json").read_text(encoding="utf-8"))["項目"]
    出 = []
    for x in kb:
        題 = x.get("題", "")
        if not 拾う.search(題) or 除く.search(題): continue
        文 = x.get("文", "")
        if len(文) < 200: continue
        # ★もう受け付けていないものに印を付ける（2026-08-28）。
        #   市は題に【受付終了】と書いている。今もらえるものと混ぜたら誤案内になる
        終わり = ("【受付終了】" in 題 or "受付終了" in 題
                  or re.search(r"受付は?終了(?:しました|いたしました)", 文[:600]) is not None)
        一 = {
            "題": 題.replace("【受付終了】", "").strip(), "url": x.get("url", ""),
            "課": x.get("課", ""), "場面": 場面(題, 文),
        }
        if 終わり: 一["受付終了"] = True
        電 = x.get("電話")
        if 電: 一["電話"] = 電[0] if isinstance(電, list) else 電
        k = 金額(文)
        if k: 一["金額の記述"] = k
        # 対象がひと目で分かる一文
        m = re.search(r"[^。\n]{0,60}(?:対象(?:者|は)?|次の(?:いずれ|すべて)|要件)[^。\n]{0,80}",文)
        if m: 一["対象の記述"] = re.sub(r"\s+", "", m.group(0))[:110]
        出.append(一)
    if not 出:
        print("！ 助成の記事が1件も無い"); return 1
    生 = [x for x in 出 if not x.get("受付終了")]
    c = Counter(s for x in 生 for s in x["場面"])
    先 = 根 / "shiso_josei.json"
    先.write_text(json.dumps({
        "作成": "市公式サイトの記事から、助成・補助・給付の案内だけを集めた",
        "件数": len(出), "いま受け付けている数": len(生),
        "項目": sorted(出, key=lambda x: x["題"])},
        ensure_ascii=False, indent=1), encoding="utf-8")
    件数を守る("助成・補助", len(出))
    print(f"○ 助成・補助 {len(出)}件（うち受付終了 {len(出)-len(生)}件）"
          f" → {先}（{先.stat().st_size//1024}KB）")
    print("  場面ごと:", dict(c.most_common()))
    金 = [x for x in 出 if "金額の記述" in x]
    対 = [x for x in 出 if "対象の記述" in x]
    print(f"  金額が読めた {len(金)}件／対象が読めた {len(対)}件")
    print("\n  例（子育て）:")
    for x in [y for y in 出 if "子育て" in y["場面"]][:6]:
        print(f"   {x['題'][:40]:42s} {x.get('金額の記述','')[:34]}")
    return 0

if __name__ == "__main__":
    sys.exit(主())
