# -*- coding: utf-8 -*-
"""宍粟市の基本の情報（面積・市の花と木・合併・市歌・市の日）

なぜ：
  「宍粟市の面積は」「市の花は何ですか」に答えられなかった。
  市を紹介する場面（10月の説明会など）でいちばん基本の問いなのに、
  市のページに散らばっていて、どれも即答の受け皿が無かった。

★数値も言葉も、市のページに書いてある通りに写す。こちらで足さない。
"""
import json, pathlib, re, sys

根 = pathlib.Path(__file__).resolve().parent.parent

def 記事(kb, 題):
    for x in kb:
        if x.get("題", "") == 題: return x
    return None

def 主():
    kb = json.loads((根 / "shiso_kb.json").read_text(encoding="utf-8"))["項目"]
    出 = {"作成": "市公式サイト『宍粟市の紹介』の各ページより", "項目": {}}
    元 = {}

    # ── 合併・沿革
    x = 記事(kb, "沿革")
    if x:
        元["沿革"] = x["url"]
        m = re.search(r"(\d+)つの町\(([^)]+)\)が(平成\d+年\d+月\d+日)に合併", x["文"])
        if m:
            出["項目"]["合併"] = {
                "日": m.group(3), "町の数": int(m.group(1)),
                "旧町": [t.strip() for t in re.split(r"[・、]", m.group(2))],
                "説明": "宍粟郡の4町（山崎町・一宮町・波賀町・千種町）が"
                        + m.group(3) + "に合併して宍粟市が誕生しました。",
            }
        出["項目"]["沿革の文"] = x["文"][:900]

    # ── 市の花・市の木
    x = 記事(kb, "市花・市木")
    if x:
        元["市花・市木"] = x["url"]
        花 = re.search(r"市花『([^』]+)』", x["文"])
        木 = re.search(r"市木『([^』]+)』", x["文"])
        if 花 and 木:
            出["項目"]["市の花と木"] = {
                "花": 花.group(1), "木": 木.group(1),
                "花の説明": (re.search(r"市花『[^』]+』をご紹介\s*(.{0,200})", x["文"])
                             or [None, ""])[1] if False else
                             x["文"].split("をご紹介")[1][:200].strip() if "をご紹介" in x["文"] else "",
            }

    # ── 宍粟の日
    x = 記事(kb, "4月1日は「宍粟の日」")
    if x:
        元["宍粟の日"] = x["url"]
        出["項目"]["宍粟の日"] = {
            "日": "4月1日",
            "説明": "宍粟市は平成17年4月1日に山崎町・一宮町・波賀町・千種町の4町が"
                    "合併して誕生しました。市民が郷土の歴史と文化を振り返る日として"
                    "4月1日を「宍粟の日」と定めています。"}

    # ── 市歌
    x = 記事(kb, "宍粟市歌「ここがふるさと」")
    if x:
        元["市歌"] = x["url"]
        m = re.search(r"制定日\s*(令和\d+年\d+月\d+日)", x["文"])
        人 = re.search(r"(\d+)人から合計(\d+)点", x["文"])
        出["項目"]["市歌"] = {
            "名前": "ここがふるさと",
            "制定日": m.group(1) if m else "",
            "経緯": (f"市民など{人.group(1)}人から{人.group(2)}点のフレーズが寄せられました。"
                     if 人 else ""),
        }

    # ── 面積（市のページの本文から。数字は書いてあるものだけ）
    面 = None
    for x in kb:
        m = re.search(r"(?:面積|総面積)[はが約、\s]{0,3}([\d,]+\.?\d*)\s*(?:平方キロメートル|㎢|km2)", x.get("文", ""))
        if m:
            面 = {"値": m.group(1), "出典の題": x.get("題", ""), "url": x.get("url", "")}
            break
    if 面:
        面["言い方"] = f"宍粟市の面積は{面['値']}平方キロメートルです。"
        # ★どこに書いてある数字かを残す（後から裏を取れるように）
        面["どこに"] = "市の『地籍調査』のページの「宍粟市の状況／概要」"
        出["項目"]["面積"] = 面

    # ★市の将来像（2026-08-28）。「宍粟市はどんなまちをめざしていますか」に
    #   答えられなかった。総合計画に定められた言葉で、市の説明の核になる
    for x in kb:
        m = re.search(r"まちの将来像「([^」]{4,40})」", x.get("文", ""))
        if m:
            出["項目"]["将来像"] = {
                "言葉": m.group(1),
                "どこに": x.get("題", ""),
                "url": x.get("url", ""),
            }
            元["将来像"] = x.get("url", "")
            break

    出["出典"] = 元
    先 = 根 / "shiso_kihon.json"
    先.write_text(json.dumps(出, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"○ 基本の情報 {len(出['項目'])}項目 → {先}（{先.stat().st_size//1024}KB）")
    for k, v in 出["項目"].items():
        if k == "沿革の文": print(f"  {k}: {len(v)}字"); continue
        print(f"  {k}: {json.dumps(v, ensure_ascii=False)[:120]}")
    足りない = [k for k in ("合併", "市の花と木", "宍粟の日", "市歌") if k not in 出["項目"]]
    if 足りない: print(f"！ 取れなかった: {足りない}")
    return 0 if not 足りない else 1

if __name__ == "__main__":
    sys.exit(主())
