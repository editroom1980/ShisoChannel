def 資料の言葉たち():
    """いま持っている資料の「名前になりうる文字」を全部集める（枝に中身があるかの確認用）。

    ★2026-09-01の失敗：最初は6ファイルしか見ておらず、当番医・郵便局・駐在所・
      民話・方言・行政区・市外からの行き方の7枝を「資料0件」として外していた。
      どれも別のファイルに実在した。**数える範囲が狭かっただけ**。
      検算そのものは正しく働いたので、範囲を全資料に広げる。
    """
    語 = []
    for f in sorted(根.glob("shiso_*.json")):
        if f.name in ("shiso_janru.json",):
            continue
        try:
            d = json.loads(f.read_text(encoding="utf-8"))
        except Exception:
            continue
        語.append(f.name)                      # ファイル名自体も手がかりになる
        def 掘る(o, 深さ=0):
            if 深さ > 3:
                return
            if isinstance(o, dict):
                for k, v in o.items():
                    if k in ("文", "本"):        # 本文は長すぎるので数えない
                        continue
                    語.append(str(k))
                    掘る(v, 深さ + 1)
            elif isinstance(o, list):
                for v in o[:4000]:
                    掘る(v, 深さ + 1)
            elif isinstance(o, str) and len(o) <= 80:
                語.append(o)
        掘る(d)
    return "\n".join(語)


def 主():
    本文 = 資料の言葉たち()
    出 = []
    空 = []
    for 親, 子ら in 木:
        枝 = []
        for 名, 問, 手がかり in 子ら:
            n = 本文.count(手がかり)
            if n == 0:
                空.append(f"{親} / {名}（手がかり「{手がかり}」の資料が0件）")
                continue
            枝.append({"名": 名, "問": 問, "資料": n})
        if 枝:
            出.append({"名": 親, "子": 枝})
    if 空:
        print("！ 資料が1件も無いので木から外した枝:", file=sys.stderr)
        for x in 空:
            print("    " + x, file=sys.stderr)
    先 = 根 / "shiso_janru.json"
    先.write_text(json.dumps({
        "説明": "ジャンルの木（暮らしの場面で分ける）。テレビの『探す』と、"
                "聞き取れなかった時に出す",
        "更新": __import__("time").strftime("%Y-%m-%dT%H:%M:%S+09:00"),
        "ジャンル数": len(出),
        "ジャンル": 出,
    }, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"ジャンル {len(出)}／枝 {sum(len(x['子']) for x in 出)} → {先}"
          f"（{先.stat().st_size // 1024}KB）")
    for x in 出:
        print(f"  {x['名']}: {len(x['子'])}枝  " +
              "／".join(f"{c['名']}({c['資料']})" for c in x["子"]))
    return 0


if __name__ == "__main__":
    sys.exit(主())
