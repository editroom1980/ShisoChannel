# -*- coding: utf-8 -*-
"""宍粟市のお祭りを広報しそうから拾う

なぜ作るか：
  「宍粟市のお祭りを教えて」に答える資料が1件も無かった（2026-08-28の実測）。
  市の観光ページにも祭りの一覧が無い（「祭」の字が0回）。
  ところが広報しそうには毎年の祭りの記事が載っている。

★捏造しないための決まり：
  ・「毎年◯月に開かれます」とは書かない。広報に載った**実際の開催**だけを残す
  ・祭りの名前は、こちらで決めずに本文から機械で拾う（3回以上出るものだけ）
  ・場所・日付は本文にある字だけを写す
"""
import json, re, pathlib, sys
from collections import Counter, defaultdict

根 = pathlib.Path(__file__).resolve().parent.parent
場所の町 = {}

# 拾った語のうち、祭りの名前でないもの（実測して除く）
除く = {"この祭り", "市内の祭り", "地域のお祭り", "冠婚葬祭", "の文化祭", "その祭り",
        "秋の祭り", "夏の祭り", "春の祭り", "各地の祭り", "伝統の祭り", "恒例の祭り",
        # ★市外の催し。広報は近隣の催しも載せるが、
        #   「宍粟市の祭り」として答えたら嘘になる（光都＝播磨科学公園都市。上郡町・佐用町）
        "光都映画祭"}

def 半角(t):
    return t.translate(str.maketrans("０１２３４５６７８９", "0123456789"))

def 名を整える(t):
    """拾った語の頭に付く「第30回」の残りや、切れた字を落とす。
       ★実測で出た誤り：「回いちのみやふるさとまつり」「磨国一宮伊和神社の秋季大祭」"""
    t = re.sub(r"^(第?\d*回|回)", "", t)
    # ★先頭のひらがなを助詞として落としてはいけない（2026-08-28の失敗）。
    #   「はが祭り」（波賀町の祭り）の『は』を助詞と見て「祭り」にしてしまい、
    #   15回も出ている祭りが一覧から丸ごと消えた。
    #   途中で切れた形は、下の「長い名前に含まれるか」で捨てられる
    return t

def 名前を集める(項):
    c = Counter()
    for x in 項:
        # ★「第30回」の回や、直前の1〜3字も一緒に見る（切れた名前を拾い直すため）
        for m in re.finditer(r"([一-鿿ぁ-んァ-ヶ]{2,14}(?:まつり|祭り|祭))(?![り])", x["文"]):
            t = 名を整える(m.group(1))
            if len(t) >= 4 and t not in 除く:
                c[t] += 1
    名 = [k for k, v in c.items() if v >= 3]
    # ★「途中で切れた形」を捨てる。長い方に含まれ、回数が近いなら切れた形とみなす
    残 = []
    for a in 名:
        if any(a != b and a in b and c[b] >= c[a] * 0.4 for b in 名):
            continue
        残.append(a)
    # ★「まつり」と「祭り」の書き分けを1つにまとめる（妙見夏まつり／妙見夏祭り）
    まとめ = {}
    for a in 残:
        鍵 = a.replace("祭り", "まつり").replace("祭", "まつり")
        if 鍵 not in まとめ or c[a] > c[まとめ[鍵]]: まとめ[鍵] = a
    残 = sorted(set(まとめ.values()), key=lambda k: -c[k])
    return 残, c

def 場所から町を作る():
    """観光の資料から「場所の名前 → 町」の表を作る。
       ★こちらで場所と町の対応を決めない。市の資料に書いてある住所だけを使う。

       ★どれを『場所の名前』とみなすか（2026-08-28に2度外して決めた）：
         ①住所の大字（「宍粟市一宮町福知」の福知）……いちばん確か
         ②施設の名前のうち、地形の言葉で終わるもの（最上山・福知渓谷・国見の森）
       「ふれあい」のような飾りの言葉は入れない。これを入れたせいで
       『国際ふれあいまつり』を一宮町の祭りだと言ってしまった"""
    表 = {}
    f = 根 / "shiso_kanko.json"
    if not f.exists(): return 表
    地形 = ("山", "川", "谷", "滝", "峠", "城", "寺", "神社", "森", "渓谷", "高原",
            "湖", "池", "岳", "原", "野", "里", "峰")
    d = json.loads(f.read_text(encoding="utf-8"))
    for x in (d.get("項目", d) if isinstance(d, dict) else d):
        住 = x.get("住所", "")
        名 = x.get("名", "")
        町 = None
        for t in ("山崎町", "一宮町", "波賀町", "千種町"):
            if t in 住: 町 = t; break
        if not 町: continue
        # ① 住所の大字（町名のうしろ、数字の手前まで）
        g = re.search(町 + r"([一-鿿ぁ-んァ-ヶ]{2,8})", 住)
        if g: 表.setdefault(g.group(1), 町)
        # ② 施設の名前が地形の言葉で終わるとき
        if 名:
            素 = re.sub(r"^(兵庫県立|県立|市立|宍粟市)\s*", "", 名)
            頭 = re.split(r"[／/・（(\s]", 素)[0]
            候 = {頭, re.sub(r"(公園|キャンプ場|コテージ村|オートキャンプ場)$", "", 頭)}
            # ★名前の途中にある地形の言葉も拾う（「最上山公園もみじ山」の最上山）。
            #   末尾だけ見ていたら鍵が『最上山公園もみじ山』になり、
            #   「最上山もみじ祭り」に一度も当たらなかった
            for g2 in re.finditer(r"([一-鿿ぁ-んァ-ヶ]{2,6}(?:渓谷|高原|の森|山|川|谷|滝|峠|城))", 素):
                候.add(g2.group(1))
            for 語 in 候:
                if len(語) >= 3 and 語.endswith(地形):
                    if 語 in 表 and 表[語] != 町: 表[語] = None   # 町がまたがる語は使わない
                    else: 表.setdefault(語, 町)
    return {k: v for k, v in 表.items() if v}


def 主():
    項 = []
    for f in ("shiso_koho.json", "shiso_koho_kako.json"):
        項 += json.loads((根 / f).read_text(encoding="utf-8"))["項目"]
    global 場所の町
    場所の町 = 場所から町を作る()
    print(f"観光の資料から『場所→町』を {len(場所の町)}件そろえた")
    名ら, 回数 = 名前を集める(項)
    print(f"祭りの名前 {len(名ら)}件を拾った")
    出 = []
    for 名 in 名ら:
        話 = []
        地区 = Counter()
        月 = Counter()
        # ★地区は、まず名前そのものから決める（いちばん確か）
        名から = None
        for か, t in (("はが", "波賀町"), ("波賀", "波賀町"), ("ちくさ", "千種町"),
                       ("千種", "千種町"), ("いちのみや", "一宮町"), ("一宮", "一宮町"),
                       ("やまさき", "山崎町"), ("山崎", "山崎町")):
            if か in 名: 名から = t; break
        # ★名前に町名が無ければ、名前に入っている「場所」で引く（2026-08-28）。
        #   「最上山もみじ祭り」の最上山は山崎町、「福知渓谷もみじ祭り」の福知渓谷は一宮町。
        #   観光の資料が持つ住所を使う＝こちらで決めずに市の資料に従う
        if not 名から:
            for 場, 町 in 場所の町.items():
                if 場 in 名: 名から = 町; break
        for x in 項:
            f = 半角(x["文"])
            for m in re.finditer(re.escape(名), f):
                s = f[max(0, m.start() - 130): m.end() + 200].replace("\n", " ")
                # ★地区は名前のすぐそば（前後40字）だけを見る。
                #   広報の1片は記事が何本も混ざるので、離れた所の地名は当てにならない
                近 = f[max(0, m.start() - 40): m.end() + 40]
                for t in ("山崎町", "一宮町", "波賀町", "千種町"):
                    if t in 近: 地区[t] += 1
                # ★月も名前のすぐ後ろ（60字以内）だけ。離れた日付は別の記事のもの
                g = re.search(r"(\d{1,2})月(\d{1,2})日", f[m.end(): m.end() + 60])
                if g and 1 <= int(g.group(1)) <= 12: 月[int(g.group(1))] += 1
                if len(話) < 4:
                    話.append({"号": x.get("号", ""), "抜粋": s.strip()[:230]})
        一 = {"名前": 名, "広報に出た回数": 回数[名], "記事": 話}
        if 名から: 一["地区"] = 名から
        elif 地区 and 地区.most_common(1)[0][1] >= 2: 一["地区"] = 地区.most_common(1)[0][0]
        if 月 and 月.most_common(1)[0][1] >= 2: 一["よく出る月"] = 月.most_common(1)[0][0]
        出.append(一)
    先 = 根 / "shiso_matsuri.json"
    先.write_text(json.dumps({"作成": "広報しそうの記事から拾った祭りの名前と記述",
                              "件数": len(出), "項目": 出},
                             ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"○ {len(出)}件 → {先}（{先.stat().st_size // 1024}KB）")
    for x in 出:
        print(f"  {x['名前']:22s} {x['広報に出た回数']:3d}回"
              f"  {x.get('地区', '（地区は不明）'):6s} {x.get('よく出る月', '?')}月ごろ")
    # 検算：どの祭りにも記事が付いているか
    空 = [x["名前"] for x in 出 if not x["記事"]]
    if 空: print(f"！ 記事の付かない祭り: {空}")
    else: print(f"検算: 全{len(出)}件に広報の記事が付いている")
    return 0

if __name__ == "__main__":
    sys.exit(主())
