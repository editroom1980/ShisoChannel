#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
宍粟市の特産品を、市の「ふるさと納税返礼品一覧」から機械的に拾う。
出力: shiso_tokusan.json

なぜ作るか（2026-08-27）：
  「宍粟市の特産品は」に答えられなかった。市のサイトに総論の記事が無いため。
  ところが返礼品の一覧（PDF・約5.7万字）に、実際に売られている宍粟の品が
  すべて載っていた。「調べれば出てくる」というユーザーの指摘のとおりだった。

★品名は手で書かない。返礼品一覧に**実際に何回出てくるか**を数え、
  多いものから並べる。数がそのまま「宍粟を代表する度合い」になる。
★説明も返礼品の文から拾う（作り話をしない）。
"""
import json, re, sys, time, pathlib

根 = pathlib.Path(__file__).resolve().parent.parent
入力 = 根 / "shiso_pdf.json"
出力 = 根 / "shiso_tokusan.json"

# 数える品目（表記ゆれをまとめる）。★これ自体は品名の候補にすぎず、
# 実際に載っていないものは0回で落ちる＝資料に無いものは出さない
品目 = [
    ("宍粟牛・但馬牛", ["宍粟牛", "但馬牛", "黒毛和牛"]),
    ("お米（キヌヒカリ・みかたの舞）", ["キヌヒカリ", "みかたの舞", "繁盛米", "コシヒカリ"]),
    ("そうめん", ["そうめん", "素麺"]),
    ("日本酒・地酒", ["日本酒", "純米", "地酒", "老松"]),
    ("鹿肉・ジビエ", ["鹿肉", "ジビエ", "しか肉"]),
    ("杉・ヒノキの木材と木工品", ["杉", "ヒノキ", "檜", "木材"]),
    ("トマト", ["トマト"]),
    ("甘酒・糀（発酵のふるさと）", ["甘酒", "糀", "こうじ"]),
    ("はちみつ", ["はちみつ", "蜂蜜"]),
    ("味噌・醤油", ["味噌", "醤油"]),
    ("鮎", ["鮎"]),
    ("ブルーベリー", ["ブルーベリー"]),
    ("森林セラピー・温泉の体験", ["森林セラピー", "温泉"]),
]


def 説明を拾う(全文, 語ら, 上限=110):
    """その品が出てくる所から、説明らしいひとかたまりを拾う。手で書かない。
       ★返礼品の一覧はPDFを文字にしたもので、句点がほとんど無い（2026-08-27の実測）。
         句点で切ろうとすると何も取れないので、改行を外した流れから取る"""
    平 = re.sub(r"\s+", "", 全文)
    for w in 語ら:
        for m in re.finditer(re.escape(w) + r".{10,100}", 平):
            t = re.sub(r"【[^】]*】", "", m.group(0))
            t = re.sub(r"\d{1,3},?\d{0,3}円", "", t)
            t = re.sub(r"[A-Z]\d{1,3}", "", t)       # 管理番号（F2・J56 など）
            t = t.strip("　 、。")
            # 「但馬牛の血統を受け継いだ黒毛和牛」のような、品の説明らしい所を採る
            if 20 <= len(t) <= 上限 and not re.search(r"容量|数量限定|時間指定|冷蔵|冷凍|セット】", t[:12]):
                return t[:上限]
    return ""


if __name__ == "__main__":
    pdf = json.loads(入力.read_text(encoding="utf-8"))
    返 = [x for x in pdf["項目"] if "返礼品" in x.get("題", "")]
    if not 返:
        print("★返礼品の資料が無い（shiso_pdf.json を作り直すこと）", file=sys.stderr)
        sys.exit(1)
    全文 = "".join(x["文"] for x in 返)
    平 = 全文.replace("\n", "")

    出 = []
    for 名, 語ら in 品目:
        数 = sum(平.count(w) for w in 語ら)
        if 数 < 3:            # ★ほとんど載っていないものは特産と呼ばない
            continue
        出.append({"名": 名, "回数": 数, "説明": 説明を拾う(全文, 語ら)})
    出.sort(key=lambda x: -x["回数"])

    if len(出) < 5:
        print(f"★{len(出)}件しか拾えていない。資料の形が変わった可能性", file=sys.stderr)
        sys.exit(1)

    出力.write_text(json.dumps({
        "更新": time.strftime("%Y-%m-%dT%H:%M:%S+09:00"),
        "出典": "宍粟市ふるさと納税返礼品一覧（市公式サイトの添付PDF）"
                "。品目は一覧に出てくる回数の多い順",
        "件数": len(出),
        "項目": 出,
    }, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")
    print(f"{len(出)}品目 → {出力}（{出力.stat().st_size//1024}KB）")
    for x in 出:
        print(f"  {x['回数']:4}回  {x['名']:26} {x['説明'][:44]}")
