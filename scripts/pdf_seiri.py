def 分野を当てる(題, 親, 課):
    素 = f"{題} {親} {課}"
    for 名, p in 分野:
        if re.search(p, 素):
            return 名
    return "その他"


def 主(表示=True):
    元 = 根 / "shiso_pdf.json"
    if not 元.exists():
        print("shiso_pdf.json が無い", file=sys.stderr)
        return 1
    d = json.loads(元.read_text(encoding="utf-8"))
    片ら = d["項目"]

    # 片（分割）ではなく、PDF1本を単位に数える
    本 = {}
    for r in 片ら:
        u = r["url"]
        if u not in 本:
            本[u] = {"題": re.sub(r"（\d+/\d+）$", "", r["題"]).replace("資料 ", "", 1),
                     "url": u, "課": r.get("課", ""), "親": r.get("親", ""),
                     "電話": r.get("電話", []), "字数": 0, "片": 0,
                     "読み取り": bool(r.get("読み取り"))}
        本[u]["字数"] += len(r.get("文", ""))
        本[u]["片"] += 1
        if r.get("読み取り"):
            本[u]["読み取り"] = True

    for v in 本.values():
        v["分野"] = 分野を当てる(v["題"], v["親"], v["課"])

    分野別 = collections.defaultdict(list)
    for v in 本.values():
        分野別[v["分野"]].append(v)

    出 = {"作った日": __import__("time").strftime("%Y-%m-%d"),
          "PDFの本数": len(本), "片の数": len(片ら),
          "字数の合計": sum(v["字数"] for v in 本.values()),
          "読み取りで救った本数": sum(1 for v in 本.values() if v["読み取り"]),
          "分野": {}}
    順 = [n for n, _ in 分野] + ["その他"]
    for 名 in 順:
        ら = 分野別.get(名, [])
        if not ら:
            continue
        課別 = collections.defaultdict(list)
        for v in sorted(ら, key=lambda x: -x["字数"]):
            課別[v["課"] or "課の記載なし"].append(
                {"題": v["題"], "url": v["url"], "字数": v["字数"], "片": v["片"],
                 "読み取り": v["読み取り"]})
        出["分野"][名] = {"本数": len(ら), "字数": sum(v["字数"] for v in ら),
                          "担当課": {k: 課別[k] for k in
                                     sorted(課別, key=lambda k: -len(課別[k]))}}

    (根 / "data_src").mkdir(exist_ok=True)
    先 = 根 / "data_src" / "pdf_mokuji.json"
    先.write_text(json.dumps(出, ensure_ascii=False, separators=(",", ":")),
                  encoding="utf-8")

    if 表示:
        print(f"PDF {出['PDFの本数']}本／{出['片の数']}片／"
              f"{出['字数の合計']:,}字"
              f"（画像から読み取って救ったもの {出['読み取りで救った本数']}本）")
        for 名, v in 出["分野"].items():
            課数 = len(v["担当課"])
            print(f"  {名}: {v['本数']}本 {v['字数']:,}字（{課数}課）")
        print(f"→ {先}（{先.stat().st_size // 1024}KB）")
    return 0


if __name__ == "__main__":
    sys.exit(主())
