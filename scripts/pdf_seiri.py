    ("給付金・補助", r"給付金|支援金|物価高騰|補助・助成|助成事業|助成金|補助金一覧|臨時特別"
                    r"|プレミアム|商品券|応援金"),
    ("ごみ・環境", r"ごみ|ゴミ|resource|資源|分別|収集|リサイクル|し尿|浄化槽|環境|公害|騒音|太陽光"),
